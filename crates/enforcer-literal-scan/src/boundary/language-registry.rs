macro_rules! spec {
    ($id:expr, $family:expr, $extensions:expr, $basenames:expr, $single:expr, $backtick:expr, $triple:expr $(,)?) => {
        LanguageSpec {
            id: LiteralLanguageName::from_static($id),
            family: $family,
            extensions: LiteralExtensionSet::from_static($extensions),
            basenames: LiteralBasenameSet::from_static($basenames),
            syntax: LiteralStringSyntaxProfile::from_bits(
                (u8::from($single) * LiteralStringSyntaxProfile::SINGLE_QUOTE)
                    | (u8::from($backtick) * LiteralStringSyntaxProfile::BACKTICK)
                    | (u8::from($triple) * LiteralStringSyntaxProfile::TRIPLE_DOUBLE),
            ),
        }
    };
}

