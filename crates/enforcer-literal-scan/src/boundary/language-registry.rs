pub(crate) fn detect_language(path: &Path, include_unknown: bool) -> Option<LanguageSpec> {
    let registry = language_registry();
    let basename = path.file_name().and_then(OsStr::to_str).unwrap_or("");
    for spec in &registry {
        if spec.basenames.as_slice().contains(&basename) {
            return Some(*spec);
        }
    }
    let ext = path.extension().and_then(OsStr::to_str).unwrap_or("");
    for spec in &registry {
        if spec
            .extensions
            .as_slice()
            .iter()
            .any(|candidate| candidate.eq_ignore_ascii_case(ext))
        {
            return Some(*spec);
        }
    }
    if include_unknown {
        Some(spec!(
            "unknown",
            LanguageFamily::Fallback,
            &[],
            &[],
            true,
            true,
            true,
        ))
    } else {
        None
    }
}
