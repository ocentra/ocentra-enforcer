use super::{LanguageFamily, LanguageSpec};
use enforcer_domain::scan_types::{
    LiteralBasenameSet, LiteralExtensionSet, LiteralLanguageName, LiteralStringSyntaxProfile,
};
use std::ffi::OsStr;
